#!/usr/bin/env node
/**
 * Generates .assetsignore for the Cloudflare Workers Static Assets deploy.
 *
 * The site is served from the repo root, but only a subset of the repo is needed
 * at runtime. This script derives that subset mechanically from the pages' own
 * references so nothing live gets excluded.
 *
 * Re-run after regenerating product/news pages:
 *   node scripts/build-assetsignore.mjs
 */

import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const MAX_ASSET_SIZE = 25 * 1024 * 1024;

const SKIP_DIRS = new Set(['.git', 'node_modules', '.commandcode', '.wrangler', '.github', 'archive']);

// Dev-only trees. Their file references are build-time only and must not be
// mistaken for things a browser loads, so they are excluded from the scan.
const DEV_DIRS = new Set(['scripts', 'script', 'tools', 'docs', 'tasks', 'templates', 'partials']);
const REF_SCAN_EXT = new Set(['.html', '.js', '.css']);

function walk(dir, onFile, skip = SKIP_DIRS) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (skip.has(entry.name)) continue;
      walk(full, onFile, skip);
    } else {
      onFile(full);
    }
  }
}

function rel(p) {
  return path.relative(ROOT, p).split(path.sep).join('/');
}

// ---------------------------------------------------------------- references
// Every path the served HTML/JS/CSS points at under data/product/. Dev trees are
// skipped so build-time references are not mistaken for browser loads.
const referenced = new Set();
const SCAN_SKIP = new Set([...SKIP_DIRS, ...DEV_DIRS]);
walk(ROOT, (full) => {
  const ext = path.extname(full);
  if (!REF_SCAN_EXT.has(ext)) return;
  const text = fs.readFileSync(full, 'utf-8');
  for (const m of text.matchAll(/data\/product\/[^"'<>\s)]+/g)) {
    referenced.add(decodeURIComponent(m[0].split(/[?#]/)[0]));
  }
}, SCAN_SKIP);

// ------------------------------------------------------- unreferenced images
const orphanImages = [];
const imagesRoot = path.join(ROOT, 'data', 'product');
if (fs.existsSync(imagesRoot)) {
  walk(imagesRoot, (full) => {
    const r = rel(full);
    if (!referenced.has(r)) orphanImages.push(r);
  });
}
orphanImages.sort();

// ------------------------------------------------------------ oversized PDFs
const oversized = [];
walk(path.join(ROOT, 'assets'), (full) => {
  if (path.extname(full).toLowerCase() !== '.pdf') return;
  if (fs.statSync(full).size > MAX_ASSET_SIZE) oversized.push(rel(full));
});
oversized.sort();

// ------------------------------------------------------------------- output
const lines = [
  '# Generated by scripts/build-assetsignore.mjs — do not hand-edit.',
  '# Re-run it after regenerating pages.',
  '',
  '# --- VCS / infrastructure ---',
  '.git/', '.wrangler/', '.commandcode/', '.github/', 'node_modules/', 'chromium/', 'tmp/',
  '',
  '# --- Dev tooling and repo docs (not served) ---',
  'scripts/', 'script/', 'tools/', 'docs/', 'tasks/', 'templates/', 'archive/', 'partials/',
  'package.json', 'package-lock.json', 'README.md', 'brand-spec.md', 'AGENTS.md', '.gitignore',
  'wrangler.jsonc', 'wrangler.json', 'wrangler.toml',
  // Worker source lives inside the assets directory; without this it would be
  // uploaded and publicly readable as a static asset.
  'worker/',
  '',
  '# --- Build-only data: fed to the generators, never fetched at runtime ---',
  'data/products/**/*.json',
  'data/articles.json', 'data/articles-skeleton.json', 'data/collections/',
  '**/products-tree.json', '**/crawl-report.json', '**/categories.json', '**/.detail-cache.json',
  '',
  `# --- Catalogue PDFs over the 25 MiB per-asset limit (${oversized.length}) — serve from R2 ---`,
  ...oversized,
  '',
  `# --- Product images not referenced by any page (${orphanImages.length}) ---`,
  ...orphanImages,
  '',
];

fs.writeFileSync(path.join(ROOT, '.assetsignore'), lines.join('\n'));

console.log(`referenced data/product paths: ${referenced.size}`);
console.log(`unreferenced product images:   ${orphanImages.length}`);
console.log(`oversized PDFs (>25 MiB):      ${oversized.length}`);
console.log(`.assetsignore lines written:   ${lines.length}`);
